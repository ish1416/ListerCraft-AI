/**
 * ListerCraft AI — 1-Click Export Hub Engine
 * Generates Etsy CSV, eBay CSV, Markdown dossiers, and printable inventory tags
 */

class ExportEngine {
  downloadFile(content, fileName, contentType) {
    const blob = new Blob([content], { type: contentType });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = fileName;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  }

  escapeCsv(val) {
    if (val === null || val === undefined) return '""';
    const str = String(val).replace(/"/g, '""');
    return `"${str}"`;
  }

  exportEtsyCSV(specs, listingData, pricing) {
    const headers = ["Title", "Description", "Price", "Quantity", "Tags", "Materials", "Section"];
    const tagsFormatted = (listingData.etsy.tags || []).join(",");
    
    const row = [
      this.escapeCsv(listingData.etsy.title),
      this.escapeCsv(listingData.etsy.copy),
      this.escapeCsv(pricing.sellingPrice.toFixed(2)),
      this.escapeCsv(1),
      this.escapeCsv(tagsFormatted),
      this.escapeCsv(specs.materials),
      this.escapeCsv(specs.category)
    ];

    const csvContent = headers.join(",") + "\n" + row.join(",");
    const fileName = `etsy_listing_${Date.now()}.csv`;
    this.downloadFile(csvContent, fileName, "text/csv;charset=utf-8;");
  }

  exportEbayCSV(specs, listingData, pricing) {
    const headers = ["Action(SiteID=US|Country=US|Currency=USD)", "CustomLabel", "Title", "StartPrice", "Quantity", "Description", "ConditionID"];
    
    const row = [
      this.escapeCsv("Add"),
      this.escapeCsv(`SKU-${Date.now().toString().slice(-6)}`),
      this.escapeCsv(listingData.ebay.title),
      this.escapeCsv(pricing.sellingPrice.toFixed(2)),
      this.escapeCsv(1),
      this.escapeCsv(listingData.ebay.copy),
      this.escapeCsv(specs.condition.includes("Brand New") ? 1000 : 3000)
    ];

    const csvContent = headers.join(",") + "\n" + row.join(",");
    const fileName = `ebay_listing_${Date.now()}.csv`;
    this.downloadFile(csvContent, fileName, "text/csv;charset=utf-8;");
  }

  exportMarkdown(specs, listingData, pricing, feeAnalysis) {
    const md = `# ${specs.title} — E-Commerce Listing Dossier
Generated by **ListerCraft AI** (Google Gemma 2 2B Open-Weights Studio)
Date: ${new Date().toLocaleDateString()}

---

## 📋 Product Specifications
- **Category:** ${specs.category}
- **Condition:** ${specs.condition}
- **Materials:** ${specs.materials}
- **Dimensions:** ${specs.dimensions}
- **Era / Style:** ${specs.era}
- **Target Audience:** ${specs.audience}

---

## 💰 Financial & Fee Analysis
- **Target Listing Price:** $${pricing.sellingPrice.toFixed(2)}
- **COGS (Sourcing Cost):** $${pricing.cogs.toFixed(2)}
- **Shipping & Packaging:** $${pricing.shipping.toFixed(2)}

### Marketplace Breakdown:
- **Etsy:** Net Profit: $${feeAnalysis.etsy.netProfit.toFixed(2)} (${feeAnalysis.etsy.marginPct.toFixed(1)}% margin) | Total Fees: $${feeAnalysis.etsy.totalFees.toFixed(2)} | Breakeven: $${feeAnalysis.etsy.breakeven.toFixed(2)}
- **eBay:** Net Profit: $${feeAnalysis.ebay.netProfit.toFixed(2)} (${feeAnalysis.ebay.marginPct.toFixed(1)}% margin) | Total Fees: $${feeAnalysis.ebay.totalFees.toFixed(2)} | Breakeven: $${feeAnalysis.ebay.breakeven.toFixed(2)}
- **Shopify:** Net Profit: $${feeAnalysis.shopify.netProfit.toFixed(2)} (${feeAnalysis.shopify.marginPct.toFixed(1)}% margin) | Total Fees: $${feeAnalysis.shopify.totalFees.toFixed(2)} | Breakeven: $${feeAnalysis.shopify.breakeven.toFixed(2)}

---

## 🌿 1. Etsy Artisan Listing
### Title:
${listingData.etsy.title}

### 13 Search Tags:
\`${(listingData.etsy.tags || []).join(", ")}\`

### Description:
${listingData.etsy.copy}

---

## 🏷️ 2. eBay PowerSeller Listing
### Title (80-Char SEO):
${listingData.ebay.title}

### Description & Item Specifics:
${listingData.ebay.copy}

---

## 🛍️ 3. Shopify & Social Copy
### Title:
${listingData.shopify.title}

### Description:
${listingData.shopify.copy}

---
*Created with ListerCraft AI — 100% Local, Private, and Zero-Cost AI for Side Hustlers.*
`;

    const fileName = `listing_dossier_${Date.now()}.md`;
    this.downloadFile(md, fileName, "text/markdown;charset=utf-8;");
  }

  printInventoryQR(specs, pricing) {
    const printWindow = window.open("", "_blank");
    const sku = `SKU-${Date.now().toString().slice(-6)}`;
    
    printWindow.document.write(`
      <!DOCTYPE html>
      <html>
      <head>
        <title>Inventory Tag — ${sku}</title>
        <style>
          body { font-family: 'Courier New', monospace; padding: 20px; text-align: center; color: #000; }
          .tag-box { border: 2px dashed #000; padding: 15px; max-width: 350px; margin: 0 auto; border-radius: 8px; }
          h2 { font-size: 16px; margin: 0 0 5px 0; text-transform: uppercase; }
          .sku { font-size: 13px; font-weight: bold; margin-bottom: 8px; letter-spacing: 2px; }
          .barcode { font-size: 30px; letter-spacing: 5px; font-weight: bold; margin: 10px 0; }
          .price { font-size: 24px; font-weight: 800; color: #000; margin: 10px 0; }
          .details { font-size: 11px; text-align: left; margin-top: 10px; border-top: 1px solid #ccc; padding-top: 6px; }
        </style>
      </head>
      <body>
        <div class="tag-box">
          <h2>ListerCraft Inventory</h2>
          <div class="sku">${sku}</div>
          <div class="barcode">||| | |||| | ||||| | |||</div>
          <div class="price">$${pricing.sellingPrice.toFixed(2)}</div>
          <div class="details">
            <div><strong>Item:</strong> ${specs.title.substring(0, 35)}...</div>
            <div><strong>Category:</strong> ${specs.category}</div>
            <div><strong>Condition:</strong> ${specs.condition}</div>
            <div><strong>Date:</strong> ${new Date().toLocaleDateString()}</div>
          </div>
        </div>
        <script>
          window.onload = function() { window.print(); };
        </script>
      </body>
      </html>
    `);
    printWindow.document.close();
  }
}

window.exportEngine = new ExportEngine();
